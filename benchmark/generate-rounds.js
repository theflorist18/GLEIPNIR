'use strict';

// Renders the offered-load create rounds of steady-standard.yaml and
// steady-anchoring.yaml FROM sweeps.yaml (the single source of truth for sweep
// constants). Run `npm run gen:rounds` after editing sweeps.yaml so the round
// configs never drift from the sweep definition (docs/CONTRACTS.md §10).
//
// It regenerates only these two files; the parallel / parallel-anchored / verify
// / smoke configs are authored directly (their parameterization is per-cell and
// handled by sweep.py).

const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const sweeps = yaml.load(fs.readFileSync(path.join(__dirname, 'sweeps.yaml'), 'utf8'));
const loads = sweeps.offered_load_tps;

function createRound(tps, mode) {
  return [
    `    - label: create-${tps}tps`,
    '      txNumber: 1000',
    '      rateControl:',
    '        type: fixed-rate',
    '        opts:',
    `          tps: ${tps}`,
    '      workload:',
    '        module: workload/createEvidence.js',
    '        arguments:',
    `          mode: ${mode}`,
    '',
  ].join('\n');
}

const standard = `# GENERATED by generate-rounds.js from sweeps.yaml — do not edit by hand.
# STEADY-STATE — Standard variant. Report SUCCESSFUL-ONLY throughput (see README).
test:
  name: gleipnir-steady-standard
  description: Standard variant steady-state — create/transfer/access under offered load.
  workers:
    number: 4
  rounds:
${loads.map((t) => createRound(t, 'fabric')).join('')}    - label: access-spread-50tps
      txNumber: 1000
      rateControl:
        type: fixed-rate
        opts:
          tps: 50
      workload:
        module: workload/accessLog.js
        arguments:
          mode: fabric
          scenario: spread
          pool: 25
    - label: transfer-50tps
      txNumber: 1000
      rateControl:
        type: fixed-rate
        opts:
          tps: 50
      workload:
        module: workload/transferCustody.js
        arguments:
          mode: fabric
          pool: 50
`;

const anchoring = `# GENERATED by generate-rounds.js from sweeps.yaml — do not edit by hand.
# STEADY-STATE — Anchoring variant (rest-mode; use networks/rest-gateway.yaml).
test:
  name: gleipnir-steady-anchoring
  description: Anchoring variant steady-state — create/access via the batcher enqueue path.
  workers:
    number: 4
  rounds:
${loads.map((t) => createRound(t, 'rest')).join('')}    - label: access-spread-50tps
      txNumber: 1000
      rateControl:
        type: fixed-rate
        opts:
          tps: 50
      workload:
        module: workload/accessLog.js
        arguments:
          mode: rest
          scenario: spread
          pool: 25
`;

fs.writeFileSync(path.join(__dirname, 'benchmarks', 'steady-standard.yaml'), standard);
fs.writeFileSync(path.join(__dirname, 'benchmarks', 'steady-anchoring.yaml'), anchoring);
console.log(`generated steady-standard.yaml + steady-anchoring.yaml from sweeps.yaml (loads: ${loads.join(', ')} tps)`);
