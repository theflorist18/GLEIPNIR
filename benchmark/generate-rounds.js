'use strict';

// Renders EVERY benchmark round config — and the multi-channel Parallel network
// configs — FROM sweeps.yaml (the single source of truth for sweep constants).
// Run `npm run gen:rounds` after editing sweeps.yaml so no round file ever
// drifts from the sweep definition (docs/CONTRACTS.md §10; audit F13/F20/F27/F38:
// previously only 2 of the round files were generated and the rest hand-drifted).
//
// Outputs (benchmarks/):
//   steady-standard.yaml               fabric, coc-main
//   steady-anchoring.yaml              rest, shared scope
//   steady-parallel-c{C}.yaml          fabric, spread across case-001..case-00C
//   steady-parallel-anchored-c{C}.yaml rest, spread across case channels
//   steady-verify.yaml                 rest, anchoring (RQ2)
//   steady-verify-c{C}.yaml            rest, parallel-anchored (RQ2)
//   smoke-{variant}.yaml               regimes.smoke shape, functional only
// Outputs (networks/):
//   parallel-c{C}.yaml                 fabric network config listing C channels
//
// Multi-channel semantics (audit F6/F24): a `channels: C` round argument makes
// the workloads spread transactions round-robin across case-001..case-00C, so
// one Caliper round drives ALL provisioned channels concurrently. txNumber is
// scaled by C so the steady-state floor (min_events_per_channel) holds PER
// channel. The Caliper-reported round throughput is therefore the AGGREGATE
// across channels; collect.py derives the (uniform by construction) per-channel
// rate as aggregate/C.

const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const sweeps = yaml.load(fs.readFileSync(path.join(__dirname, 'sweeps.yaml'), 'utf8'));
const loads = sweeps.offered_load_tps;
const channelCounts = sweeps.channel_counts;
const steadyTx = sweeps.regimes.steady.min_events_per_channel;
const smoke = sweeps.regimes.smoke;

const GEN = '# GENERATED by generate-rounds.js from sweeps.yaml — do not edit by hand.';

// ---- YAML fragment builders (string-built so output stays diff-stable) ----

function rnd(label, countLines, rateLines, module, args) {
  return [
    `    - label: ${label}`,
    ...countLines,
    '      rateControl:',
    ...rateLines,
    '      workload:',
    `        module: ${module}`,
    '        arguments:',
    ...Object.entries(args).map(([k, v]) => `          ${k}: ${v}`),
    '',
  ].join('\n');
}

const txNumber = (n) => [`      txNumber: ${n}`];
const txDuration = (s) => [`      txDuration: ${s}`];
const fixedRate = (tps) => ['        type: fixed-rate', '        opts:', `          tps: ${tps}`];
const fixedLoad = (load, startTps) => [
  '        type: fixed-load', '        opts:', `          transactionLoad: ${load}`, `          startTps: ${startTps}`,
];

function benchFile(name, description, workers, rounds, extraHeader) {
  return [
    GEN,
    ...(extraHeader ? [extraHeader] : []),
    'test:',
    `  name: ${name}`,
    `  description: ${description}`,
    '  workers:',
    `    number: ${workers}`,
    '  rounds:',
    rounds.join(''),
  ].join('\n');
}

function write(rel, content) {
  fs.writeFileSync(path.join(__dirname, rel), content);
  console.log(`generated ${rel}`);
}

// ---- steady: standard + anchoring (single shared channel) ----

write('benchmarks/steady-standard.yaml', benchFile(
  'gleipnir-steady-standard',
  'Standard variant steady-state — create/transfer/access under offered load.',
  4,
  [
    ...loads.map((t) => rnd(`create-${t}tps`, txNumber(steadyTx), fixedRate(t), 'workload/createEvidence.js', { mode: 'fabric' })),
    rnd('access-spread-50tps', txNumber(steadyTx), fixedRate(50), 'workload/accessLog.js', { mode: 'fabric', scenario: 'spread', pool: 25 }),
    rnd('transfer-50tps', txNumber(steadyTx), fixedRate(50), 'workload/transferCustody.js', { mode: 'fabric', pool: 50 }),
  ],
  '# STEADY-STATE — Standard variant. Report SUCCESSFUL-ONLY throughput (see README).',
));

write('benchmarks/steady-anchoring.yaml', benchFile(
  'gleipnir-steady-anchoring',
  'Anchoring variant steady-state — create/access via the batcher enqueue path.',
  4,
  [
    ...loads.map((t) => rnd(`create-${t}tps`, txNumber(steadyTx), fixedRate(t), 'workload/createEvidence.js', { mode: 'rest' })),
    rnd('access-spread-50tps', txNumber(steadyTx), fixedRate(50), 'workload/accessLog.js', { mode: 'rest', scenario: 'spread', pool: 25 }),
  ],
  '# STEADY-STATE — Anchoring variant (rest-mode; use networks/rest-gateway.yaml).',
));

// ---- steady: parallel + parallel-anchored (one file per channel count) ----

for (const c of channelCounts) {
  write(`benchmarks/steady-parallel-c${c}.yaml`, benchFile(
    `gleipnir-steady-parallel-c${c}`,
    `Parallel steady-state — load spread across ${c} case channel(s), fabric write path.`,
    4,
    [
      ...loads.map((t) => rnd(`create-${t}tps-c${c}`, txNumber(steadyTx * c), fixedRate(t), 'workload/createEvidence.js', { mode: 'fabric', channels: c })),
      rnd(`access-spread-50tps-c${c}`, txNumber(steadyTx * c), fixedRate(50), 'workload/accessLog.js', { mode: 'fabric', scenario: 'spread', pool: 25, channels: c }),
    ],
    `# STEADY-STATE — Parallel variant, ${c}-channel cell. One round drives ALL ${c}\n# channels concurrently (round-robin); use networks/parallel-c${c}.yaml.`,
  ));

  write(`benchmarks/steady-parallel-anchored-c${c}.yaml`, benchFile(
    `gleipnir-steady-parallel-anchored-c${c}`,
    `Parallel-Anchored steady-state — per-case enqueue across ${c} channel(s) -> anchor roots.`,
    4,
    [
      ...loads.map((t) => rnd(`create-${t}tps-c${c}`, txNumber(steadyTx * c), fixedRate(t), 'workload/createEvidence.js', { mode: 'rest', channels: c })),
      rnd(`access-spread-50tps-c${c}`, txNumber(steadyTx * c), fixedRate(50), 'workload/accessLog.js', { mode: 'rest', scenario: 'spread', pool: 25, channels: c }),
    ],
    `# STEADY-STATE — Parallel-Anchored variant, ${c}-channel cell (rest-mode; use\n# networks/rest-gateway.yaml). K is set via BATCH_K by sweep.py.`,
  ));
}

// ---- steady: verification latency (RQ2) ----

const verifyHeader = '# STEADY-STATE — VERIFICATION latency (thesis RQ2): fetch receipt -> recompute\n# branch -> compare anchored root, driven through the gateway (rest connector;\n# use networks/rest-gateway.yaml). Seeding + /flush happen in the untimed init.';

write('benchmarks/steady-verify.yaml', benchFile(
  'gleipnir-steady-verify',
  'Verification/audit latency under load (fetch -> recompute branch -> compare root).',
  4,
  [
    rnd('verify-50tps', txNumber(steadyTx), fixedRate(50), 'workload/verify.js', { seedCount: 100 }),
    rnd('verify-fixed-load', txDuration(60), fixedLoad(5, 50), 'workload/verify.js', { seedCount: 100 }),
  ],
  verifyHeader,
));

for (const c of channelCounts) {
  write(`benchmarks/steady-verify-c${c}.yaml`, benchFile(
    `gleipnir-steady-verify-c${c}`,
    `Verification latency, Parallel-Anchored ${c}-channel cell (seeds spread per case).`,
    4,
    [
      rnd(`verify-50tps-c${c}`, txNumber(steadyTx), fixedRate(50), 'workload/verify.js', { seedCount: 100, channels: c }),
      rnd(`verify-fixed-load-c${c}`, txDuration(60), fixedLoad(5, 50), 'workload/verify.js', { seedCount: 100, channels: c }),
    ],
    verifyHeader,
  ));
}

// ---- smoke: regimes.smoke shape — functional correctness ONLY ----
// cases evidence items; logs_per_case_max accesses each. Never cite for
// performance (CLAUDE.md). Labels are smoke-*; sweep.py keeps smoke- runIds.

const smokeHeader = '# SMOKE test — functional correctness only (regimes.smoke: '
  + `${smoke.cases} cases x ${smoke.logs_per_case_min}-${smoke.logs_per_case_max} logs). `
  + 'Its results MUST NOT be\n# cited for any scalability/throughput claim (CLAUDE.md, ARCHITECTURE §8).';

function smokeRounds(mode, channels) {
  const spread = channels ? { channels } : {};
  return [
    rnd('smoke-create', txNumber(smoke.cases), fixedRate(5), 'workload/createEvidence.js', { mode, ...spread }),
    rnd('smoke-logs', txNumber(smoke.cases * smoke.logs_per_case_max), fixedRate(25), 'workload/accessLog.js', { mode, scenario: 'spread', pool: smoke.cases, ...spread }),
  ];
}

const smokeVerifyRound = (channels) => rnd(
  'smoke-verify',
  txNumber(smoke.cases * smoke.logs_per_case_min),
  fixedRate(10),
  'workload/verify.js',
  { seedCount: smoke.cases, ...(channels ? { channels } : {}) },
);

write('benchmarks/smoke-standard.yaml', benchFile(
  'gleipnir-smoke-standard',
  'Smoke functional check of the Standard variant (create + logs + shared-access gate).',
  2,
  [
    ...smokeRounds('fabric'),
    // Stage-1 gate in miniature: many workers, one shared evidence, zero conflicts.
    rnd('smoke-access-shared-gate', txNumber(200), fixedRate(50), 'workload/accessLog.js', { mode: 'fabric', scenario: 'shared', sharedEvidenceId: 'ev-shared-gate' }),
  ],
  smokeHeader,
));

write('benchmarks/smoke-anchoring.yaml', benchFile(
  'gleipnir-smoke-anchoring',
  'Smoke functional check of the Anchoring variant (enqueue + verify round-trip).',
  2,
  [...smokeRounds('rest'), smokeVerifyRound()],
  smokeHeader,
));

write('benchmarks/smoke-parallel.yaml', benchFile(
  'gleipnir-smoke-parallel',
  'Smoke functional check of the Parallel variant (single case channel).',
  2,
  smokeRounds('fabric', 1),
  smokeHeader + '\n# Single-channel smoke (case-001); use networks/parallel-c1.yaml.',
));

write('benchmarks/smoke-parallel-anchored.yaml', benchFile(
  'gleipnir-smoke-parallel-anchored',
  'Smoke functional check of the Parallel-Anchored variant (per-case enqueue + verify).',
  2,
  [...smokeRounds('rest', 1), smokeVerifyRound(1)],
  smokeHeader + '\n# Single-channel smoke (case-001); use networks/rest-gateway.yaml.',
));

// ---- networks: multi-channel Parallel configs (fabric mode) ----
// Channel names are deterministic (case-001..case-00C), so these are fully
// static; the channels must be provisioned (provision-channel.sh) before use.

for (const c of channelCounts) {
  const channelBlocks = Array.from({ length: c }, (_, i) => [
    `  - channelName: case-${String(i + 1).padStart(3, '0')}`,
    '    contracts:',
    '      - id: evidence',
  ].join('\n')).join('\n');
  write(`networks/parallel-c${c}.yaml`, [
    GEN,
    `# Multi-channel Caliper network config — Parallel variant, ${c}-channel cell.`,
    `name: GLEIPNIR parallel-c${c}`,
    'version: "2.0.0"',
    '',
    'caliper:',
    '  blockchain: fabric',
    '',
    'channels:',
    channelBlocks,
    '',
    'organizations:',
    '  - mspid: Org1MSP',
    '    identities:',
    '      certificates:',
    '        - name: User1',
    '          clientPrivateKey:',
    '            path: ../network/organizations/peerOrganizations/org1.example.com/users/User1@org1.example.com/msp/keystore/priv_sk',
    '          clientSignedCert:',
    '            path: ../network/organizations/peerOrganizations/org1.example.com/users/User1@org1.example.com/msp/signcerts/cert.pem',
    '    connectionProfile:',
    '      path: networks/connection-org1.yaml',
    '      discover: false',
    '',
  ].join('\n'));
}

console.log(`gen:rounds complete (loads: ${loads.join(', ')} tps; channels: ${channelCounts.join(', ')}; steady tx/channel: ${steadyTx}; smoke: ${smoke.cases}x${smoke.logs_per_case_min}-${smoke.logs_per_case_max})`);
